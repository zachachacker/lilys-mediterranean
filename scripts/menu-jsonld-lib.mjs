// Builds the menu.html JSON-LD (schema.org Menu) from data.js, so Google can
// show dishes and prices in search. Pure: takes the data.js source, returns
// the JSON text. Prices are the ONLINE prices, the same ones menu.html shows.
// Used by scripts/menu-jsonld.mjs (writes menu.html) and seo_test.ts (checks it).
const DIET = { Vegan: "https://schema.org/VeganDiet", Veg: "https://schema.org/VegetarianDiet" };

export function menuJsonLd(dataJsSource) {
  const window = {};
  new Function("window", `${dataJsSource}; return window;`)(window);
  const L = window.LILYS;
  const sections = L.MENU.map((cat) => ({
    "@type": "MenuSection",
    name: cat.c,
    hasMenuItem: cat.items.map(([name, desc, price, tag]) => {
      const item = { "@type": "MenuItem", name };
      if (desc) item.description = desc;
      const m = /^\$(\d+)\.(\d{2})$/.exec(price);
      if (m) item.offers = { "@type": "Offer", price: (L.onlineCents(Number(m[1]) * 100 + Number(m[2])) / 100).toFixed(2), priceCurrency: "USD" };
      if (DIET[tag]) item.suitableForDiet = DIET[tag];
      return item;
    }),
  }));
  return JSON.stringify({
    "@context": "https://schema.org",
    "@type": "Menu",
    "@id": "https://lilysmediterraneanfresh.com/menu.html#menu",
    name: "Lily's Mediterranean Fresh Grill menu",
    url: "https://lilysmediterraneanfresh.com/menu.html",
    inLanguage: "en-US",
    hasMenuSection: sections,
  }).replace(/</g, "\\u003c"); // a "</script>" inside a description can't end the block
}

export const START = "<!-- menu-jsonld:start (generated by scripts/menu-jsonld.mjs, do not edit) -->";
export const END = "<!-- menu-jsonld:end -->";
